    fun forSoc(socName: String?): GpuModelInfo? {
        val normalized = socName?.lowercase(Locale.US)?.trim().orEmpty()
        if (normalized.isEmpty()) return null
        return entries.firstOrNull { entry -> entry.tokens.any(normalized::contains) }?.model
    }
